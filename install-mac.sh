#!/bin/sh
# Download and inspect this script before running it. No sudo or developer tools.
set -eu
base='@RELEASE_URL@'
public_key='@PUBLIC_KEY@'
case "$base" in https://*) ;; *) echo 'Use the published install.sh, generated by scripts/build_release.py.' >&2; exit 2;; esac
[ "$(uname -s)" = Darwin ] && [ "$(uname -m)" = arm64 ] || { echo 'Requires Apple Silicon and macOS 15 or newer.' >&2; exit 1; }
major=$(sw_vers -productVersion | cut -d . -f 1)
[ "$major" -ge 15 ] || { echo 'Requires macOS 15 or newer.' >&2; exit 1; }
# The global lock prevents two installers from replacing each other's backup.
user_tmp=$(getconf DARWIN_USER_TEMP_DIR)
lock="${user_tmp}multiswitcher-install.lock"
mkdir -m 700 "$lock" 2>/dev/null || { echo 'Another MultiSwitcher installer is running. If it was interrupted, remove the temporary multiswitcher-install.lock directory.' >&2; exit 1; }
tmp=$(mktemp -d "${user_tmp}multiswitcher-install-XXXXXX")
destination=/Applications/MultiSwitcher.app
staged="/Applications/.multiswitcher-new-$$.app"
backup="/Applications/.multiswitcher-previous-$$.app"
installed=0
moved=0
success=0
was_running=0
cleanup() {
  if [ "$success" -eq 0 ]; then
    # Never delete a running app after a launch timeout. Leave both copies for recovery.
    if [ "$installed" -eq 1 ] && pgrep -x MultiSwitcher >/dev/null; then
      echo "Startup not confirmed. Previous app preserved at $backup" >&2
    else
      if [ "$installed" -eq 1 ]; then rm -rf "$destination"; fi
      if [ "$moved" -eq 1 ] && [ ! -e "$destination" ]; then mv "$backup" "$destination"; fi
      if [ "$was_running" -eq 1 ] && [ -e "$destination" ]; then open -g "$destination" || true; fi
    fi
  fi
  rm -rf "$tmp" "$staged"
  rmdir "$lock" 2>/dev/null || true
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
curl --proto '=https' --proto-redir '=https' --tlsv1.2 -fsSL --max-time 60 --max-filesize 65536 "$base/latest.json" -o "$tmp/latest.json"
version=$(plutil -extract version raw -o - "$tmp/latest.json")
build=$(plutil -extract build raw -o - "$tmp/latest.json")
bytes=$(plutil -extract bytes raw -o - "$tmp/latest.json")
checksum=$(plutil -extract sha256 raw -o - "$tmp/latest.json")
archive=$(plutil -extract archive raw -o - "$tmp/latest.json")
[ "$(plutil -extract updater_public_key raw -o - "$tmp/latest.json")" = "$public_key" ]
case "$version" in ''|*[!0-9.]*|.*|*..*|*.) exit 1;; esac
case "$build:$bytes" in *[!0-9:]*) exit 1;; esac
[ "$build" -gt 0 ] && [ "$bytes" -gt 0 ] && [ "$bytes" -le 1073741824 ]
[ "$archive" = "MultiSwitcher-$version-$build-arm64.zip" ]
[ "${#checksum}" -eq 64 ]
case "$checksum" in *[!0-9a-f]*) exit 1;; esac
printf 'Downloading MultiSwitcher %s…\n' "$version"
curl --proto '=https' --proto-redir '=https' --tlsv1.2 -fsSL --max-time 600 --max-filesize "$bytes" "$base/$archive" -o "$tmp/app.zip"
[ "$(stat -f %z "$tmp/app.zip")" -eq "$bytes" ]
[ "$(shasum -a 256 "$tmp/app.zip" | awk '{print $1}')" = "$checksum" ]
# Reject traversal, unexpected roots, links escaping the app, and oversized archives.
zipinfo -1 "$tmp/app.zip" > "$tmp/paths"
awk 'BEGIN {bad=0} /^\// || /\\/ || /(^|\/)\.\.(\/|$)/ {bad=1} !/^MultiSwitcher\.app\// && !/^__MACOSX\// {bad=1} END {exit bad || NR == 0 || NR > 50000}' "$tmp/paths"
zipinfo -l "$tmp/app.zip" > "$tmp/entries"
awk '/^[-dl]/ {total += $4} END {exit total > 2147483648}' "$tmp/entries"
# Framework links may contain .., but their normalized target must stay in the app.
sed -n 's/^l[^ ]* *[^ ]* *[^ ]* *[^ ]* *[^ ]* *[^ ]* *[^ ]* *[^ ]* *[^ ]* *//p' "$tmp/entries" > "$tmp/links"
while IFS= read -r path; do
  link=$(unzip -p "$tmp/app.zip" "$path")
  case "$link" in ''|/*|*\\*) echo 'Invalid archive link' >&2; exit 1;; esac
  printf '%s/%s\n' "${path%/*}" "$link" | awk -F/ '{n=0; for(i=1;i<=NF;i++){if($i=="..")n--;else if($i!="." && $i!="")n++;if(n<1)exit 1}}'
done < "$tmp/links"
ditto -x -k "$tmp/app.zip" "$tmp"
app="$tmp/MultiSwitcher.app"
info="$app/Contents/Info.plist"
[ "$(plutil -extract CFBundleIdentifier raw -o - "$info")" = com.multiswitcher.app ]
[ "$(plutil -extract CFBundleVersion raw -o - "$info")" = "$build" ]
[ "$(plutil -extract CFBundleShortVersionString raw -o - "$info")" = "$version" ]
[ "$(plutil -extract SUPublicEDKey raw -o - "$info")" = "$public_key" ]
[ "$(plutil -extract SUFeedURL raw -o - "$info")" = "$base/appcast.xml" ]
codesign --verify --deep --strict "$app"
"$app/Contents/MacOS/MultiSwitcher" --selftest
if [ "${1:-}" = --verify-only ]; then success=1; echo "Verified download, archive, application and updater configuration."; exit 0; fi
if [ -e "$destination" ] || [ -L "$destination" ]; then
  [ ! -L "$destination" ]
  [ "$(plutil -extract CFBundleIdentifier raw -o - "$destination/Contents/Info.plist")" = com.multiswitcher.app ]
  old_build=$(plutil -extract CFBundleVersion raw -o - "$destination/Contents/Info.plist")
  case "$old_build" in ''|*[!0-9]*) echo 'Cannot compare installed build.' >&2; exit 1;; esac
  [ "$build" -ge "$old_build" ] || { echo 'Refusing to install an older build.' >&2; exit 1; }
fi
ditto "$app" "$staged"
codesign --verify --deep --strict "$staged"
if pgrep -x MultiSwitcher >/dev/null; then
  was_running=1
  # Respect applicationShouldTerminate: active conversions must finish first.
  osascript -e 'tell application id "com.multiswitcher.app" to quit'
  for attempt in $(seq 1 60); do pgrep -x MultiSwitcher >/dev/null || break; sleep 1; done
  if pgrep -x MultiSwitcher >/dev/null; then echo 'MultiSwitcher is still processing files. Try again after it finishes.' >&2; exit 1; fi
fi
if [ -e "$destination" ]; then mv "$destination" "$backup"; moved=1; fi
mv "$staged" "$destination"
installed=1
# This release has no Apple notarization; only clear quarantine on this verified app.
xattr -dr com.apple.quarantine "$destination" 2>/dev/null || true
open -g "$destination" --args --install-health "$tmp/ready"
ready=0
for attempt in $(seq 1 30); do
  if [ -f "$tmp/ready" ] &&
     [ "$(plutil -extract version raw -o - "$tmp/ready" 2>/dev/null)" = "$version" ] &&
     [ "$(plutil -extract build raw -o - "$tmp/ready" 2>/dev/null)" = "$build" ]; then ready=1; break; fi
  sleep 1
done
[ "$ready" -eq 1 ] || { echo 'Could not confirm startup.' >&2; exit 1; }
success=1
# Keep one manual fallback. Do not erase the only working previous version.
if [ "$moved" -eq 1 ]; then printf 'Previous app kept at %s\n' "$backup"; fi
printf 'MultiSwitcher %s installed and running.\n' "$version"
